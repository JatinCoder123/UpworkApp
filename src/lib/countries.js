// Lower case, without accents, dots, punctuation or a leading "the": "U.S.A." → "usa", "Côte d’Ivoire" → "cote d ivoire".
export const normalizeCountry = (text) => asText(text).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
  .replace(/\./g, '').replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, ' ').trim().replace(/^the /, '')

// Every name a country goes by, normalized; "Saint …" also as "St …".
export const countryNames = ([, ...names]) => names.map(normalizeCountry).flatMap((name) => (name.startsWith('saint ') ? [name, name.replace(/^saint /, 'st ')] : [name]))

const CODE_BY_NAME = new Map(COUNTRIES.flatMap((country) => countryNames(country).map((name) => [name, country[0]])))

// The ISO code for a client country as the CRM or Upwork wrote it, or '' when it is not a country we know (some CRM
// jobs hold a city there). For "Sydney, Australia" the part after the last comma is tried too.
export function countryCode(text) {
  return CODE_BY_NAME.get(normalizeCountry(text)) || CODE_BY_NAME.get(normalizeCountry(asText(text).split(',').at(-1))) || ''
}
